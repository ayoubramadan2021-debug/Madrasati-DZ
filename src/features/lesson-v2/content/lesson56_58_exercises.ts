import type {
  TapSelectImageItem,
} from "../exercises-v2/TapSelectImagesV2";

import type {
  FourTapExercises,
} from "../exercises-v2/World3TapTextExercisesV2";

type CorrectIndex =
  | 0
  | 1
  | 2
  | 3;

type Options = readonly [
  string,
  string,
  string,
  string,
];

type Row = readonly [
  question: string,
  options: Options,
  correctIndex: CorrectIndex,
];

function buildExercise(
  prefix: string,
  rows: readonly Row[],
): TapSelectImageItem[] {
  return rows.map(
    (
      [
        question,
        options,
        correct_index,
      ],
      index,
    ) => ({
      question,
      question_audio_key:
        `${prefix}_q${index + 1}`,
      options: [...options],
      correct_index,
      image_fit: "contain",
    }),
  );
}

